"""Summarize only measured local artifacts; does not run or fabricate benchmarks."""

import json
from pathlib import Path
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
evaluation = json.loads((root / "reports/evaluation.json").read_text())
retrieval = json.loads((root / "reports/retrieval.json").read_text())
acceptance = json.loads((root / "reports/acceptance.json").read_text())
deployment = json.loads((root / "reports/deployment.json").read_text())
suite = ET.parse(root / "reports/tests.xml").getroot().find("testsuite")
summary = evaluation["summary"]
lines = [
    "# Measured local results",
    "",
    "These results are from synthetic fixture runs, not clinical validation or live-model benchmarks. Reports are regenerated by the documented commands; no paid provider calls or cloud deployment were performed.",
    "",
    f"Unit/integration tests: **{suite.attrib['tests']} tests**, **{suite.attrib['failures']} failures**, **{suite.attrib['errors']} errors**, {float(suite.attrib['time']):.2f} seconds. See `reports/tests.xml`.",
    "",
    f"Full browser acceptance: **{'passed' if acceptance.get('passed') else 'failed'}**. See `reports/acceptance.json`.",
    "",
    "| Acceptance check | Observed result |",
    "|---|---|",
]
for name, check in acceptance["checks"].items():
    lines.append(f"| {name} | {'passed' if check['passed'] else 'failed'} |")
if acceptance.get("error"):
    lines += ["", f"Failure: `{acceptance['error']}`"]
if acceptance.get("dashboard_import_error"):
    lines += ["", f"Dashboard import warning: `{acceptance['dashboard_import_error']}`"]
lines += [
    "",
    "## Held-out workflow evaluation",
    "",
    f"{evaluation['scenarios']} scenarios × {evaluation['trials']} trials × two architectures. Dataset: `{evaluation['dataset_version']}`; SHA-256 `{evaluation['dataset_sha256']}`.",
    "",
    "| Metric | Single controller | Three agents |",
    "|---|---:|---:|",
]
metrics = [
    ("Runs", "runs", "int"),
    ("Expected end-to-end outcome", "success_rate", "pct"),
    ("Field accuracy before correction", "field_accuracy", "pct"),
    ("Fields evaluated", "field_count", "int"),
    ("Patient/identity outcome", "patient_match", "pct"),
    ("Retrieval relevance", "retrieval_relevant", "pct"),
    ("Citation correctness", "citation_correct", "pct"),
    ("Final persisted transaction", "final_transaction_correct", "pct"),
    ("Policy adherence", "policy_adherent", "pct"),
    ("Duplicate prevention", "duplicate_prevented", "pct"),
    ("Repeated outcome consistency", "repeat_consistency", "pct"),
    ("Mean latency (ms)", "mean_latency_ms", "float"),
    ("Provider tokens", "tokens", "int"),
    ("Estimated provider cost (USD)", "estimated_cost_usd", "float"),
]
for title, key, fmt in metrics:
    values = []
    for architecture in ["single", "multi"]:
        value = summary[architecture][key]
        values.append(
            f"{value * 100:.2f}%" if fmt == "pct" else f"{value:.2f}" if fmt == "float" else str(value)
        )
    lines.append(f"| {title} | {values[0]} | {values[1]} |")
lines += [
    "",
    "Expected outcomes include safe escalations and clarification, not only successful writes. The evaluation uses real API/agent/database code with in-process simulated MCP/UI transport; the acceptance suite separately uses real MCP and Chromium. Pharmacist corrections are scripted fixture actions. Low extraction accuracy on unknown blurry scans and deliberately missing/conflicting fields remains visible before those corrections.",
    "",
    "There is no observed fixture quality advantage for the multi-agent design. Small latency differences are local timing noise, not a model-performance conclusion. Live evaluations and judge calibration remain **pending**. Human labels have not been invented.",
    "",
    "## Retrieval-only evaluation",
    "",
    f"{retrieval['queries']} queries; recall@3 **{retrieval['recall_at_3'] * 100:.1f}%**, MRR **{retrieval['mrr']:.2f}**, citation integrity **{retrieval['citation_correctness'] * 100:.1f}%**. Stale-version, wrong-tenant and modified-policy blocking: {retrieval['adversarial_checks']}. This measures the SQLite lexical/hashed-vector fixture fallback independently of answer generation.",
    "",
    "## Deployment and unverified integrations",
    "",
    f"Static deployment configuration: `{deployment['static_config']}`. Compose execution: `{deployment['compose_config']}`. Cloud: `{deployment['live_cloud']}`.",
    "",
    "Not locally verified: PostgreSQL/pgvector queries and checkpoint execution, container image startup, Jaeger startup, cloud DNS/HTTPS, backup restoration, live text/vision/embedding/STT/TTS calls, and LLM judge calibration. Mocked provider contract tests are not live integration tests.",
    "",
    "The frontend TypeScript check and Vite production build were executed successfully. Two upstream deprecation warnings remain in Python tests (Starlette test transport and LangGraph serializer defaults); they do not change the recorded pass/fail results.",
    "",
]
if "negative_abstention_accuracy" in retrieval:
    lines += ["## Expanded evidence and observed limitations", "",
              f"Retrieval negative set: {len(retrieval['negative_queries'])} queries; abstention accuracy **{retrieval['negative_abstention_accuracy']:.1%}**. Keyword-overlapping off-topic queries remain a measured weakness; the held-out queries were not used to tune a new threshold.", ""]
for filename in ["evaluation-v2.json", "unseen.json"]:
    path = root / "reports" / filename
    if path.exists():
        extra = json.loads(path.read_text())
        if "summary" in extra:
            lines += [f"Additional workflow set `{extra['dataset_version']}`: {extra['scenarios']} scenarios × {extra['trials']} trials × two architectures.", "",
                      "| Architecture | Runs | Expected outcome | Extraction before scripted correction | Mean latency |",
                      "|---|---:|---:|---:|---:|"]
            for architecture, row in extra["summary"].items():
                lines.append(f"| {architecture} | {row['runs']} | {row['success_rate']:.1%} | {row['field_accuracy']:.2%} | {row['mean_latency_ms']:.2f} ms |")
            lines += ["", f"Scenario-cluster Wilson 95% interval (single): {extra['summary']['single'].get('scenario_success_wilson_95')}. Trials are grouped by their {extra['scenarios']} scenarios, not counted as independent samples. Synthetic sampling does not estimate real-world clinical performance.", ""]
        elif "per_field" in extra:
            lines += [f"Unseen extraction-only set: {extra['samples']} documents × {extra['trials']} trials, {extra['mode']} mode. Live evaluation is separate.", "", "| Field | Before correction | Samples |", "|---|---:|---:|"]
            for field, row in extra["per_field"].items():
                lines.append(f"| {field} | {row['accuracy_before_correction']:.2%} | {row['n']} |")
            lines += ["", "No human correction scores are reported for this extraction-only suite. Known-hash fixtures are excluded; poor unknown-image fixture accuracy is expected and is not evidence of live vision quality.", ""]
lines += ["Historical reports are retained under `reports/historical/original-v1/`. An intermediate deduplication-context evaluation failure is retained in `reports/historical/dedup-context-regression.json`; the harness was corrected to isolate trial encounters. Live model/judge reports explicitly say skipped. The user selected fixture-only completion; no paid calls were made.", ""]
(root / "docs/RESULTS.md").write_text("\n".join(lines), encoding="utf8")
print("Generated docs/RESULTS.md from actual report files.")
